# Writes lua/species.lua (national dex number -> name) from the pokebw2 decomp's generated/species.txt.
# Usage: python3 scripts/gen_species.py <pokebw2>/generated/species.txt lua/species.lua
import sys
fix = {'NIDORAN_F': 'Nidoran♀', 'NIDORAN_M': 'Nidoran♂', 'MR_MIME': 'Mr. Mime', 'MIME_JR': 'Mime Jr.',
       'FARFETCHD': "Farfetch'd", 'HO_OH': 'Ho-Oh', 'PORYGON_Z': 'Porygon-Z', 'PORYGON2': 'Porygon2',
       'TYPE_NULL': 'Type: Null'}
names = [l.split('=')[0].strip()[8:] for l in open(sys.argv[1]) if l.startswith('SPECIES_')]
with open(sys.argv[2], 'w', encoding='utf-8', newline='\n') as f:
    f.write('-- Generated by scripts/gen_species.py from the pokebw2 decomp. Species id -> name.\nreturn {\n')
    for i, n in enumerate(names[:650]):
        if i == 0: continue
        f.write(f'  [{i}] = "{fix.get(n, n.replace("_", " ").title())}",\n')
    f.write('}\n')
