# Writes lua/mmo_code.lua: the built in-game code as hex, where it goes and its entry points.
import sys
bin_path, syms_path, out_path = sys.argv[1:4]
data = open(bin_path, 'rb').read()
syms = {}
for line in open(syms_path):
    parts = line.split()
    if len(parts) == 3:
        syms[parts[2]] = int(parts[0], 16)
base = 0x01FFA400
end = syms['__image_end']
with open(out_path, 'w', newline='\n') as f:
    f.write('-- Generated by scripts/build.sh from arm/. Do not edit.\n')
    f.write('return {\n')
    f.write(f'  base = 0x{base:08X},\n')
    f.write(f'  size = 0x{end - base:X}, -- code + data + bss (bss is zeroed)\n')
    f.write(f'  provider = 0x{syms["mmo_provider"] | 1:08X},\n')
    f.write('  hex = "' + data.hex().upper() + '",\n')
    f.write('}\n')
print(f'mmo code: {len(data)} bytes, {end - base} with bss, provider 0x{syms["mmo_provider"]:08X}')
