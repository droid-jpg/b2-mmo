# Writes lua/zones.lua (zone id -> readable place) from the pokebw2 decomp's generated/zones.txt.
# Usage: python3 scripts/gen_zones.py <pokebw2>/generated/zones.txt lua/zones.lua
import re, sys
names = [l.split('=')[0].strip() for l in open(sys.argv[1]) if l.startswith('ZONE_')]
small = {'Of', 'The', 'And'}
def pretty(z):
    words = re.sub(r'_\d+$', '', z[5:]).split('_')
    out = []
    for w in words:
        w = w.capitalize()
        if w == 'Pokemon': w = 'Pokémon'
        if w in small and out: w = w.lower()
        out.append(w)
    s = ' '.join(out)
    return re.sub(r'\b(\d+)f\b', r'\1F', s).replace('Route ', 'Route ').replace('B1f', 'B1F')
with open(sys.argv[2], 'w', encoding='utf-8', newline='\n') as f:
    f.write('-- Generated by scripts/gen_zones.py from the pokebw2 decomp. Zone id -> place.\nreturn {\n')
    for i, z in enumerate(names):
        f.write(f'  [{i}] = "{pretty(z)}",\n')
    f.write('}\n')
print(len(names), 'zones')
